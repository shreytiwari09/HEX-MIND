const test = require('node:test')
const assert = require('node:assert/strict')
const { createUserStore, register, login, userFor } = require('../src/auth')
const { addTodo, listTodos, toggleTodo } = require('../src/userTodos')

test('register validates and refuses duplicates', () => {
  const s = createUserStore()
  assert.throws(() => register(s, 'nope', 'longenough'), { message: 'invalid email' })
  assert.throws(() => register(s, 'a@x.io', 'short'), { message: 'password too short' })
  const u = register(s, 'a@x.io', 'longenough')
  assert.equal(u.email, 'a@x.io')
  assert.ok(u.id !== undefined)
  assert.throws(() => register(s, 'A@X.io', 'longenough'), { message: 'email taken' })
})

test('login needs the right password and the password is not stored as given', () => {
  const s = createUserStore()
  register(s, 'a@x.io', 'longenough')
  assert.throws(() => login(s, 'a@x.io', 'wrongpass1'), { message: 'invalid credentials' })
  assert.throws(() => login(s, 'b@x.io', 'longenough'), { message: 'invalid credentials' })
  const token = login(s, 'a@x.io', 'longenough')
  assert.equal(typeof token, 'string')
  assert.equal(userFor(s, token).email, 'a@x.io')
  assert.equal(userFor(s, 'bogus'), null)
  assert.ok(!JSON.stringify(s).includes('longenough'))
})

test('users only see and change their own todos', () => {
  const s = createUserStore()
  register(s, 'a@x.io', 'longenough')
  register(s, 'b@x.io', 'longenough')
  const a = login(s, 'a@x.io', 'longenough')
  const b = login(s, 'b@x.io', 'longenough')
  addTodo(s, a, '  buy milk ')
  addTodo(s, b, 'walk dog')
  assert.deepEqual(listTodos(s, a).map((t) => t.title), ['buy milk'])
  assert.deepEqual(listTodos(s, b).map((t) => t.title), ['walk dog'])
  assert.throws(() => addTodo(s, a, '   '), { message: 'title required' })
  assert.throws(() => listTodos(s, 'bogus'), { message: 'not logged in' })
  toggleTodo(s, a, 1)
  assert.equal(listTodos(s, a)[0].done, true)
  assert.equal(listTodos(s, b)[0].done, false)
  assert.throws(() => toggleTodo(s, a, 99), { message: 'todo not found' })
})
